import type { PassengerKind } from './PassengerTypes';
import type { BossKind } from './bosses';

export interface LevelDef {
  id: number;
  stationEn: string;
  stationZh: string;
  flavourEn: string;
  flavourZh: string;
  density: number; // 0–10
  timer: number; // seconds
  /** Relative weights for special spawns */
  mix: Partial<Record<PassengerKind, number>>;
  /** Boarding pressure: 0–1 for regular levels; >1 = event surge (L100). */
  pressure: number;
  playable: boolean;
  /** Show a full intro card before the timer (first time / always on this level id). */
  introKind?: PassengerKind;
  /** Small HUD tip chip while playing (reinforce / remind). */
  tipKind?: PassengerKind;
  /** v0.7: override how many door bays open (default by level id: 3 → 2 from L8 → 1 from L16). 2 = relief level. */
  openDoors?: 1 | 2 | 3;
  /** v0.7: exam level (L99 final approach): all special types mixed. */
  exam?: boolean;
  /** v0.7: boss level — one oversized "king" per listed type (L20–L90 every 10; all eight at L100). */
  boss?: BossKind[];
}

