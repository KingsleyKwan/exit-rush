/** Level id that must be cleared before L100 unlocks (v0.7: was 30 → now 99). */
export const FINALE_UNLOCK_AFTER = 99;

export function getLevel(id: number): LevelDef | undefined {
  return LEVELS.find((l) => l.id === id);
}

export function playableLevels(): LevelDef[] {
  return LEVELS.filter((l) => l.playable);
}

/** How many agents to spawn from density 0–10 */
export function crowdCount(density: number): number {
  // v0.6: denser cars (was 6 + d·3.2). Cap soft via maxBodies.
  return Math.round(7 + density * 3.6);
}

/**
 * True if the player may start the fireworks finale. `highestCleared` counts L100 itself, so check
 * the cleared list for 99 explicitly. Players who already beat L100 before v0.7 keep it unlocked.
 */
export function isFinaleUnlocked(cleared: number[], _highestCleared?: number): boolean {
  return cleared.includes(FINALE_UNLOCK_AFTER) || cleared.includes(100);
}
